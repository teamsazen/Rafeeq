#!/usr/bin/env python3
"""Writes the native app's strings.xml from the Flutter app's .arb files.

    python3 scripts/arb_to_android_strings.py

lib/l10n/app_en.arb becomes native/.../values/strings.xml and app_ur.arb
becomes values-ur/strings.xml. Names stay the same as the .arb keys, so
R.string.appTitle is appTitle. {name} placeholders become %1$s, %2$s… in the
order the English text uses them, and ICU plurals become <plurals>.
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "native/app/src/main/res"
PLURAL = re.compile(r"\{(\w+),\s*plural,\s*((?:[^{}]|\{[^{}]*(?:\{[^{}]*\}[^{}]*)*\})*)\}")
CASE = re.compile(r"(=1|=0|one|other|zero|two|few|many)\s*\{((?:[^{}]|\{[^{}]*\})*)\}")


def escape(text: str) -> str:
    text = text.replace("\\", "\\\\").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if text.startswith(("@", "?")):
        text = "\\" + text
    return text


def placeholders(text: str, order: list[str]) -> str:
    text = text.replace("%", "%%")
    return re.sub(r"\{(\w+)\}", lambda m: f"%{order.index(m[1]) + 1}$s" if m[1] in order else m[0], text)


def names_in(text: str) -> list[str]:
    seen: list[str] = []
    for name in re.findall(r"\{(\w+)[,}]", text):
        if name not in seen:
            seen.append(name)
    return seen


def convert(arb: dict, english: dict) -> str:
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             "<!-- Generated by scripts/arb_to_android_strings.py from lib/l10n. Do not edit. -->",
             "<resources>"]
    for key, value in arb.items():
        if key.startswith("@"):
            continue
        order = names_in(english.get(key, value))
        plural = PLURAL.search(value)
        if plural:
            lines.append(f'    <plurals name="{key}">')
            for case, body in CASE.findall(plural[2]):
                quantity = {"=1": "one", "=0": "zero"}.get(case, case)
                whole = value[: plural.start()] + body + value[plural.end():]
                lines.append(f'        <item quantity="{quantity}">{escape(placeholders(whole, order))}</item>')
            lines.append("    </plurals>")
        else:
            lines.append(f'    <string name="{key}">{escape(placeholders(value, order))}</string>')
    lines.append("</resources>")
    return "\n".join(lines) + "\n"


def main() -> None:
    english = json.loads((ROOT / "lib/l10n/app_en.arb").read_text(encoding="utf-8"))
    for locale, folder in (("en", "values"), ("ur", "values-ur")):
        arb = json.loads((ROOT / f"lib/l10n/app_{locale}.arb").read_text(encoding="utf-8"))
        out = RES / folder / "strings.xml"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(convert(arb, english), encoding="utf-8")
        print(f"{out.relative_to(ROOT)}: {sum(1 for k in arb if not k.startswith('@'))} strings")


if __name__ == "__main__":
    main()
